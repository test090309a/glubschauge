def vendor_for(mac: str) -> str:
    """Liefert einen lesbaren Vendor-Namen für eine MAC-Adresse.

    Fallback: 'Lokale MAC' bei randomisierten (Bit 2 im ersten Oktett gesetzt),
    sonst 'Unbekannt'.
    """
    mac_l = mac.lower().strip()
    oui = mac_l[:8]                       # "xx:xx:xx"
    if oui in OUI_VENDORS:
        return OUI_VENDORS[oui]

    # Randomisierte MAC erkennen: zweites Bit des ersten Oktetts ist 1
    try:
        first_octet = int(mac_l[:2], 16)
        if first_octet & 0x02:
            return "Lokale MAC (randomisiert)"
    except (ValueError, IndexError):
        pass

    return "Unbekannt"